const messages: Record<Locale, Record<keyof typeof zhCN, string>> = {
  "zh-CN": zhCN,
  en,
};

export type TranslationKey = keyof typeof zhCN;

export function isLocale(value: string | undefined): value is Locale {
  return value !== undefined && (LOCALES as readonly string[]).includes(value);
}

export function localeFromValue(value: string | undefined): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

export function t(locale: Locale, key: TranslationKey, values?: TranslationValues) {
  return messages[locale][key].replace(/{{(\w+)}}/g, (_, name: string) => String(values?.[name] ?? ""));
}

export function localeToHtmlLang(locale: Locale) {
  return locale === "en" ? "en" : "zh-CN";
}
